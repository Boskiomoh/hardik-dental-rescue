// Builds audit/before-schema.sql: the ORIGINAL database, replayed into a
// separate "before" schema so the untouched app can run next to the fixed one
// in the same Supabase project.
//
// - Migrations are read from the upstream commit with git, never from the
//   working tree, so later fixes can't leak into the "before" copy.
// - The only additions are the base tables the upstream migrations forget
//   (supabase/migrations/20250801000000_base_tables.sql) and the grants a
//   Lovable-era project gave anon/authenticated by default.
// - public.* is renamed to before.*, and the auth.users trigger gets its own
//   name so it doesn't replace the fixed app's trigger.
//
// Usage: node audit/build-before-schema.mjs [upstreamRef]

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const UPSTREAM_REF = process.argv[2] ?? "8cf9b704a6027ace80d9310001c512c181ad43e5";

const git = (...args) => execFileSync("git", args, { encoding: "utf8" });

const upstreamFiles = git("ls-tree", "--name-only", `${UPSTREAM_REF}:supabase/migrations`)
  .split("\n")
  .filter((name) => name.endsWith(".sql"))
  .sort();

const baseTables = readFileSync("supabase/migrations/20250801000000_base_tables.sql", "utf8");

const toBeforeSchema = (sql) =>
  sql
    .replace(/\bpublic\./gi, "before.")
    .replace(/search_path = public\b/gi, "search_path = before")
    .replace(/\bon_auth_user_created\b/g, "before_on_auth_user_created");

const parts = [
  "-- GENERATED by audit/build-before-schema.mjs. Do not edit by hand.",
  `-- Source: upstream commit ${UPSTREAM_REF}, supabase/migrations/*`,
  "",
  "DROP SCHEMA IF EXISTS before CASCADE;",
  "CREATE SCHEMA before;",
  "GRANT USAGE ON SCHEMA before TO anon, authenticated, service_role;",
  "ALTER DEFAULT PRIVILEGES IN SCHEMA before GRANT ALL ON TABLES TO anon, authenticated, service_role;",
  "ALTER DEFAULT PRIVILEGES IN SCHEMA before GRANT ALL ON FUNCTIONS TO anon, authenticated, service_role;",
  "ALTER DEFAULT PRIVILEGES IN SCHEMA before GRANT ALL ON SEQUENCES TO anon, authenticated, service_role;",
  "SET search_path = before, extensions, public;",
  "",
  "-- ===== base tables (reconstructed; see supabase/migrations/20250801000000_base_tables.sql)",
  toBeforeSchema(baseTables),
];

for (const file of upstreamFiles) {
  const sql = git("show", `${UPSTREAM_REF}:supabase/migrations/${file}`);
  parts.push("", `-- ===== upstream ${file}`, toBeforeSchema(sql).trimEnd() + ";");
}

parts.push(
  "",
  "-- ===== Lovable-era default grants",
  "GRANT ALL ON ALL TABLES IN SCHEMA before TO anon, authenticated, service_role;",
  "GRANT ALL ON ALL FUNCTIONS IN SCHEMA before TO anon, authenticated, service_role;",
  "GRANT ALL ON ALL SEQUENCES IN SCHEMA before TO anon, authenticated, service_role;",
  "NOTIFY pgrst, 'reload schema';",
  ""
);

writeFileSync("audit/before-schema.sql", parts.join("\n"));
console.log(`Wrote audit/before-schema.sql from ${upstreamFiles.length} upstream migrations`);
